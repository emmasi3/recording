/*
问题总结
--------
在 Visual Studio 2026 中直接运行项目时，程序的当前工作目录通常是解决方案/项目目录；而双击 `x64\Debug\recording.exe` 启动时，程序的当前工作目录往往会变成可执行文件所在目录。

由于代码里使用的是相对路径 `./data_out/av/test_Muxer_Streamer.mp4`，所以两种启动方式下，`avio_open()` 解析到的实际路径不同，导致 VS 内运行正常，而直接双击 exe 时提示“找不到指定目录”。

原因分析
--------
1. 相对路径依赖当前工作目录，而不是依赖源代码所在目录。
2. IDE 启动和双击 exe 启动，工作目录经常不同。
3. `avio_open()` 本身并不是不能打开文件，根因是路径起点不一致。

解决思路
--------
1. 绝对路径
   - 直接改成完整绝对路径，定位最稳定。
   - 但当前场景涉及中文路径、编码处理以及 FFmpeg / 底层 API 兼容问题，改动成本较高。

2. 调整相对路径层级
   - 例如尝试 `../../data_out/av/test_Muxer_Streamer.mp4`。
   - 这种方式只能适配某一种启动目录，仍然依赖当前工作目录，不够稳妥。

3. 统一资源位置到 exe 同级目录
   - 将文件放到 `./test_Muxer_Streamer.mp4`。
   - 程序始终从可执行文件同级目录读取资源，不再依赖 IDE 的默认工作目录。
   - 这是当前最简单、最稳定的方案。

补充建议
--------
- 如果后续还会读取更多资源，建议统一封装资源路径的获取逻辑。
- 可以在程序启动时打印当前工作目录，便于快速定位相对路径问题。
- 如果必须使用相对路径，最好显式设置工作目录，或基于程序所在目录拼接资源路径。

最终结论
--------
本问题的根因不是文件本身不存在，而是启动方式不同导致工作目录不同。
当前采用把媒体文件放到 exe 同级目录，并使用 `./test_Muxer_Streamer.mp4` 的方式，可以有效避免 IDE 运行和双击 exe 运行结果不一致的问题。
*/